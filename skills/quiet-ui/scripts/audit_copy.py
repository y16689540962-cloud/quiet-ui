#!/usr/bin/env python3
"""audit_copy.py -- find "explanatory small print" tells in a UI page.

Counts the copy tells that make a screen read as AI-generated: eyebrows,
subtitles, helper text, captions, dot-chains, footer noise, fake badges,
summary blocks, marketing adjectives and meta-copy.

The point is measurement, not judgement: run the same script on every arm of
an experiment so the numbers are comparable. It is a heuristic regex pass and
it will both over- and under-report; every finding is a place to look, not a
verdict. A line containing `audit:ok` is skipped.

Usage:
    python3 audit_copy.py page.html
    python3 audit_copy.py builds/*/index.html --json
    python3 audit_copy.py . --budget 1      # exit 1 if a file exceeds budget
"""

import argparse
import json
import os
import re
import sys
from html.parser import HTMLParser

SKIP_TAGS = {"script", "style", "title", "code", "pre", "svg", "head"}
CAPTION_TAGS = {"figcaption"}

