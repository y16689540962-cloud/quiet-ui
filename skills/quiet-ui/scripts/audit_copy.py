EMPTY_CTX = re.compile(r"empty|no-result|noresult|zero-state", re.I)
CARD_MASK = re.compile(r"[•*·]{3,}\s*\d{4}")
BADGE_CLASS = re.compile(r"badge|pill|chip|\btag\b|rounded-full|bg-\w+-100", re.I)

# Which dimension a rule belongs to, and how specific it is. Structure wins over
# the vague "looks like small print" rule so one string is never counted twice.
RULE_GROUP = {
    "R7-marketing": "lang", "R8-claim": "lang",
    "R3-separator-chain": "chrome", "R11-badge": "chrome",
}
RULE_PRIO = {
    "R1-eyebrow": 10, "R2-numbering": 20, "R10-restate": 30, "R16-placeholder-dup": 30,
    "R4-subtitle": 40, "R9-meta": 45, "R5-helper": 50, "R6-greeting": 55,
    "R12-footer": 60, "R13-disclaimer": 65, "R14-summary": 70, "R15-caption": 75,
    "R17-testimonial": 15, "R18-bridge": 25, "R19-notice": 35, "R20-description": 12, "R21-arrow": 40,
}


class Run:
    """One run of visible text with just enough context to judge it."""

    __slots__ = ("tag", "cls", "text", "line", "attrs", "prev", "ctx")

    def __init__(self, tag, cls, text, line, attrs=None, prev=None, ctx=""):
        self.tag = tag
        self.cls = cls or ""
        self.text = text
        self.line = line
        self.attrs = attrs or {}
        self.prev = prev
        self.ctx = ctx


class Extractor(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []
        self.runs = []
        self.skip_depth = 0
        self.pending_placeholder = []
        self.buf = []
        self.buf_line = 0
        self.buf_tag = ""
        self.buf_cls = ""
        self.buf_attrs = {}

    # -- helpers
    def _open(self, tag, attrs):
        info = {"tag": tag, "cls": " ".join(v for k, v in attrs if k == "class" and v),
                "attrs": {k: v for k, v in attrs if v}}
        self.stack.append(info)
        if tag in SKIP_TAGS:
            self.skip_depth += 1
        if tag == "input" or tag == "textarea":
            ph = info["attrs"].get("placeholder")
            if ph:
                self.pending_placeholder.append((ph.strip(), self.getpos()[0]))

    def _flush(self):
        text = re.sub(r"\s+", " ", "".join(self.buf)).strip()
        if text:
            prev = self.runs[-1] if self.runs else None
            ctx = " ".join(i["cls"] for i in self.stack[-4:] if i["cls"])
            self.runs.append(Run(self.buf_tag, self.buf_cls, text, self.buf_line, self.buf_attrs, prev, ctx))
        self.buf = []
        self.buf_tag = ""
        self.buf_cls = ""
        self.buf_attrs = {}

    def handle_starttag(self, tag, attrs):
        self._flush()
        self._open(tag, attrs)

    def handle_startendtag(self, tag, attrs):
        self._flush()
        self._open(tag, attrs)
        self.stack.pop()
        if tag in SKIP_TAGS:
            self.skip_depth -= 1

    def handle_endtag(self, tag):
        self._flush()
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i]["tag"] == tag:
                for info in self.stack[i:]:
                    if info["tag"] in SKIP_TAGS:
                        self.skip_depth -= 1
                del self.stack[i:]
                break

    def handle_data(self, data):
        if self.skip_depth or not data.strip():
            return
        if not self.buf:
            self.buf_line = self.getpos()[0]
            top = self.stack[-1] if self.stack else {"tag": "", "cls": "", "attrs": {}}
            self.buf_tag = top["tag"]
            self.buf_cls = top["cls"]
            self.buf_attrs = top["attrs"]
        self.buf.append(data)

    def close(self):
        super().close()
        self._flush()


JSX_TEXT = re.compile(r">([^<>{}]{3,})<")
JSX_ATTR = re.compile(r"""\b(placeholder|aria-label|alt)\s*=\s*["']([^"']+)["']""")


def extract_jsx(source):
    """Best-effort text runs for .tsx/.jsx/.vue/.svelte: no real parser."""
    runs = []
    for m in JSX_TEXT.finditer(source):
        text = re.sub(r"\s+", " ", m.group(1)).strip()
        if not text or len(text) < 3:
            continue
        line = source.count("\n", 0, m.start()) + 1
        before = source[max(0, m.start() - 300):m.start()]
        tag = ""
        tm = re.findall(r"<([A-Za-z][\w.]*)", before)
        if tm:
            tag = tm[-1]
        cls = ""
        cm = re.findall(r'className\s*=\s*["\']([^"\']*)["\']', before)
        if cm:
            cls = cm[-1]
        runs.append(Run(tag.lower(), cls, text, line))
    placeholders = [(m.group(2).strip(), source.count("\n", 0, m.start()) + 1) for m in JSX_ATTR.finditer(source)]
    return runs, placeholders


def is_heading(run):
    return bool(re.fullmatch(r"h[1-6]", run.tag or ""))


def has(pat_list, text):
    for pat in pat_list:
        if re.search(pat, text, re.I):
            return True
    return False


def analyse(runs, placeholders, source):
    findings = []
    lines = source.splitlines()

    # One rule per dimension per text run. A subtitle that is also marketing
    # filler is two problems, but an eyebrow counted twice is noise.
    picked = {}

    def add(run, rule, why):
        group = RULE_GROUP.get(rule, "struct")
        prio = RULE_PRIO.get(rule, 50)
        key = (id(run), group)
        seen = picked.get(key)
        if seen is not None and seen["prio"] <= prio:
            return
        if 0 < run.line <= len(lines) and "audit:ok" in lines[run.line - 1]:
            return
        picked[key] = {"prio": prio, "line": run.line, "rule": rule,
                       "text": run.text[:110], "why": why}

    label_texts = [(r.text.lower(), r.line) for r in runs if (r.tag or "").lower() == "label"]
    heading_seen = False
    last_heading = ""

    for i, run in enumerate(runs):
        low = run.text.lower()
        tag = (run.tag or "").lower()
        nxt = runs[i + 1] if i + 1 < len(runs) else None
        is_title = is_heading(run) and re.fullmatch(r"h[1-2]", tag or "") and not heading_seen
        if is_title:
            heading_seen = True

        # R1 eyebrow: tiny tracked/uppercase label that names the page instead of saying something
        if not is_heading(run) and tag not in ("a", "button", "label", "th", "td"):
            if UPPERCASE_CLASS.search(run.cls) and len(run.text) <= 48:
                add(run, "R1-eyebrow", "uppercase/tracked label above or beside real content")

        # R2 numbering: 01 //, 02, Step 3
        if has(NUMBERING, run.text):
            add(run, "R2-numbering", "decorative step number with no real sequence")

        # R3 dot/pipe chain
        seps = len(DOTCHAIN.findall(run.text)) + len(PIPECHAIN.findall(run.text))
        data_ctx = bool(DATA_CTX.search(run.ctx)) or bool(CARD_MASK.search(run.text))
        segs_all = [x.strip() for x in re.split(r"[·•|]", run.text)]
        words = [x for x in segs_all if re.search(r"[A-Za-z\u4e00-\u9fff]{2,}", x)
                 and not re.fullmatch(r"[\d\s.,:%¥$€£+\-–—]*\s*(月|日|年|分钟|小时|秒|项|个|天|周|MB|GB|KB|ms)?", x)]
        is_data_pair = not words
        if data_ctx or is_data_pair:
            seps = 0
        if seps >= 2 and len(run.text) <= 160:
            add(run, "R3-separator-chain", "{} separators gluing facts into one string".format(seps))
        elif seps == 1 and len(run.text) <= 80 and tag not in ("a", "nav"):
            segs = [s.strip() for s in re.split(r"[·•|]", run.text)]
            if len(segs) == 2 and all(0 < len(s) <= 26 for s in segs):
                add(run, "R3-separator-chain", "two fragments glued by a separator")

        # R17 testimonial with attribution: content the page cannot source
        if tag in ("p", "span", "div", "blockquote", "q", "cite") and TESTIMONIAL.match(run.text) and len(run.text) >= 24:
            add(run, "R17-testimonial", "quote presented as a real customer, no source on screen")
        if ATTRIBUTION.match(run.text) and len(run.text) <= 60:
            prev_run = run.prev
            if prev_run is not None and TESTIMONIAL.match(prev_run.text):
                add(run, "R17-testimonial", "attribution line for an unsourced quote")

        # R19 tip / notice box: information the layout should carry instead
        if tag not in ("a", "button", "label", "td", "th") and 8 <= len(run.text) <= 220:
            if NOTICE_CLASS.search(run.cls) or NOTICE_CLASS.search(run.ctx):
                in_empty = EMPTY_CTX.search(run.ctx) or EMPTY_CTX.search(run.cls)
                if not in_empty and not NOTICE_EXEMPT.search(run.cls) and not NOTICE_EXEMPT.search(run.ctx):
                    add(run, "R19-notice", "tip/notice box around an explanation")

        # R20 shadcn description components: the canonical "second line under a title"
        if tag.lower() in SHADCN_DESC and len(run.text) >= 12:
            add(run, "R20-description", "Card/Alert/DialogDescription is the tell by construction")

        # R21 decoration arrow after a link or button label
        if ARROW.search(run.text) and len(run.text) <= 80:
            add(run, "R21-arrow", "arrow decorating a label instead of carrying meaning")

        # R18 bridge word between option groups
        if has(BRIDGE, run.text) and 6 <= len(run.text.strip()) <= 30 and tag not in ("label", "th"):
            add(run, "R18-bridge", "sentence connector used as UI chrome")

        # R4 subtitle: sentence right under the page title
        if nxt is run and False:
            pass
        prev = run.prev
        if prev is not None and is_heading(prev) and re.fullmatch(r"h[12]", (prev.tag or "").lower()):
            if tag in ("p", "div", "span") and len(run.text) >= 25:
                add(run, "R4-subtitle", "sentence under the page title; the title should stand alone")

        # R5 helper / instruction text
        if EMPTY_CTX.search(run.ctx) or EMPTY_CTX.search(run.cls):
            pass
        elif tag == "small" or SMALL_CLASS.search(run.cls) and len(run.text) > 12:
            if not is_heading(run) and tag not in ("label", "th", "td", "a", "button"):
                add(run, "R5-helper", "muted supporting line under a field, card or control")
        elif has(INSTRUCTION_START, run.text) and len(run.text) <= 120:
            add(run, "R5-helper", "tells the reader what the control already says")

        # R6 greeting
        if has(GREETING, run.text) and len(run.text) <= 40:
            add(run, "R6-greeting", "greeting with no information")

        # R7 marketing
        if has(MARKETING, run.text):
            add(run, "R7-marketing", "adjectival filler")

        # R8 invented claim
        if has(CLAIMS, run.text):
            add(run, "R8-claim", "number or endorsement that has no source on screen")

        # R9 meta / self-describing copy
        if has(META, run.text):
            add(run, "R9-meta", "the screen describing itself")

        # R10 restates its own heading (the heading may be interrupted by a badge)
        head = last_heading.lower().rstrip(":.") if last_heading else ""
        if head and len(head) > 3 and len(run.text) > 60 and tag in ("p", "div", "span", "li"):
            if head in low[:48]:
                add(run, "R10-restate", "paragraph opens by repeating its own heading")
        if prev is not None and is_heading(prev) and len(run.text) > 60:
            head2 = prev.text.lower().rstrip(":.")
            if head2 and len(head2) > 3 and low.startswith(head2):
                add(run, "R10-restate", "paragraph opens by repeating its own heading")
        if is_heading(run) and len(run.text) > 2:
            last_heading = run.text

        # R11 fixed badge
        if tag in ("span", "div", "sup", "em", "b") and low.strip(" !") in BADGE_WORDS:
            add(run, "R11-badge", "badge whose state is hard-coded, not data-bound")

        # R12 footer noise
        if has(FOOTER_NOISE, run.text) and len(run.text) <= 80:
            add(run, "R12-footer", "footer credit / stack line")

        # R13 disclaimer tag
        if has(DISCLAIMER, run.text) and len(run.text) <= 120:
            add(run, "R13-disclaimer", "demo-data / for-reference tag")

        # R14 summary block
        if re.fullmatch(r"[^.!?]{0,24}", run.text) and has([p.replace("^", "") for p in SUMMARY_HEADS], run.text) and len(run.text) <= 24:
            add(run, "R14-summary", "wraps up a page that already ended")

        # R15 caption under media
        if tag in CAPTION_TAGS:
            add(run, "R15-caption", "figure caption explaining the picture")

    # R16 placeholder repeats the label
    for ph, line in placeholders:
        norm = re.sub(r"^(enter|type|input|e\.g\.|eg|请输入|输入)\s*", "", ph.strip().lower()).strip()
        for label, _ in label_texts:
            lab = label.strip().rstrip(":：*")
            if not lab:
                continue
            if norm and (norm == lab or (lab in norm and len(lab) >= 4)):
                findings.append({"line": line, "rule": "R16-placeholder-dup",
                                 "text": ph[:110], "why": "placeholder repeats the visible label '{}'".format(label[:40])})
                break

    findings.extend({"line": v["line"], "rule": v["rule"], "text": v["text"], "why": v["why"]}
                    for v in picked.values())
    findings.sort(key=lambda f: (f["line"], f["rule"]))
    # de-duplicate the same line+rule (nested elements re-emit the same string)
    seen, out = set(), []
    for f in findings:
        key = (f["line"], f["rule"], f["text"])
        if key not in seen:
            seen.add(key)
            out.append(f)
    return out


def audit_file(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        source = fh.read()
    ext = os.path.splitext(path)[1].lower()
    if ext in (".html", ".htm", ".svg", ".xml"):
        parser = Extractor()
        parser.feed(source)
        parser.close()
        runs, placeholders = parser.runs, parser.pending_placeholder
    else:
        runs, placeholders = extract_jsx(source)
    return analyse(runs, placeholders, source), len(runs)


def main():
    ap = argparse.ArgumentParser(description="Count AI-copy tells in a UI page.")
    ap.add_argument("paths", nargs="+", help="files or directories")
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    ap.add_argument("--budget", type=int, default=None, help="exit 1 if a file is over this many tells")
    ap.add_argument("--quiet", action="store_true", help="summary only")
    args = ap.parse_args()

    targets = []
    for p in args.paths:
        if os.path.isdir(p):
            for root, _, files in os.walk(p):
                for name in sorted(files):
                    if os.path.splitext(name)[1].lower() in (".html", ".htm", ".jsx", ".tsx", ".vue", ".svelte"):
                        targets.append(os.path.join(root, name))
        else:
            targets.append(p)
    if not targets:
        sys.exit("no page files found")

    report, over = [], False
    for path in targets:
        findings, runs = audit_file(path)
        report.append({"file": path, "tells": len(findings), "text_runs": runs, "findings": findings})
        if args.budget is not None and len(findings) > args.budget:
            over = True

    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        for item in report:
            print("\n{}  tells={}  text_runs={}".format(item["file"], item["tells"], item["text_runs"]))
            if args.quiet:
                continue
            for f in item["findings"]:
                print("  L{:<5} {:<22} {}".format(f["line"], f["rule"], f["text"]))
        total = sum(i["tells"] for i in report)
        print("\n{} file(s), {} tell(s) total{}".format(
            len(report), total, "" if args.budget is None else ", budget {}".format(args.budget)))
    sys.exit(1 if over else 0)


if __name__ == "__main__":
    main()
